from __future__ import annotations

import asyncio
import glob
import json
import logging
import os
import shutil
import signal
from pathlib import Path
from typing import Any

from app.auditors.base import BaseAuditor, AuditModuleResult

logger = logging.getLogger(__name__)

REPORTS_BASE_DIR = Path("/app/reports")
# Previous run's screenshots/results are parked here before unlighthouse-ci wipes its output
# folder, so the visual-diff step can compare this run's pages with the last run's.
HISTORY_DIR = REPORTS_BASE_DIR / "_history"

# Lighthouse routes per run. "full" scope can mean hundreds of URLs; the HTML checks cover all of
# them, but running Chrome against each is hours of work for little extra signal, so Lighthouse
# samples the first N (pages first, then posts — the crawler already orders them that way).
LH_MAX_ROUTES_FULL = 60
# Two Chrome workers: four was the default on this 8-core host and, with other audits running,
# starved Lighthouse's own CPU measurement and tripped sites' rate limiters.
LH_MAX_CONCURRENCY = 2

# PageSpeed Insights' mobile lab settings. Matching them makes our per-page numbers comparable
# with Google's single-page PSI number instead of reading systematically higher.
PSI_MOBILE_THROTTLING = {
    "rttMs": 150,
    "throughputKbps": 1638.4,
    "requestLatencyMs": 562.5,
    "downloadThroughputKbps": 1474.56,
    "uploadThroughputKbps": 675,
    "cpuSlowdownMultiplier": 4,
}

_CONFIG_TEMPLATE = """// Generated by wpaudit; do not edit. See app/auditors/unlighthouse.py.
export default {
  cache: false,
  puppeteerClusterOptions: { maxConcurrency: %(concurrency)d },
  scanner: { samples: 1, throttle: true, device: 'mobile', dynamicSampling: false },
  lighthouseOptions: {
    throttlingMethod: 'simulate',
    throttling: %(throttling)s,
    onlyCategories: ['performance', 'accessibility', 'best-practices', 'seo'],
  },
}
"""

# Lighthouse accessibility audits worth surfacing by name (the rest are noise for a marketing
# site). Keyed by audit id -> short human label.
A11Y_AUDIT_LABELS = {
    "color-contrast": "Low contrast text",
    "image-alt": "Images without alt text",
    "link-name": "Links without a readable name",
    "button-name": "Buttons without a readable name",
    "label": "Form fields without labels",
    "frame-title": "Iframes without a title",
    "heading-order": "Heading levels skip",
    "html-has-lang": "Page has no lang attribute",
    "document-title": "Page has no title",
    "aria-allowed-attr": "Invalid ARIA attributes",
    "aria-required-attr": "Missing required ARIA attributes",
    "list": "Malformed lists",
    "tap-targets": "Tap targets too small",
    "target-size": "Tap targets too small",
    "meta-viewport": "Viewport blocks zooming",
}


def _safe_domain(site_url: str) -> str:
    return site_url.replace("https://", "").replace("http://", "").replace("/", "_").replace(":", "_")


def _route_dir(route_path: str) -> str:
    return route_path.strip("/")


def _ms(audit: dict[str, Any] | None) -> float | None:
    if not audit or audit.get("numericValue") is None:
        return None
    return round(float(audit["numericValue"]), 0)


def parse_lighthouse_json(path: Path) -> dict[str, Any]:
    """Pull the parts of one route's lighthouse.json that matter for a site owner: core metrics,
    failed/blocked asset requests, console errors, named accessibility failures and the
    third parties that cost main-thread time. Returns {} if the file is missing or unreadable."""
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except Exception:
        return {}
    audits = data.get("audits") or {}
    out: dict[str, Any] = {}

    out["metrics"] = {
        "lcp_ms": _ms(audits.get("largest-contentful-paint")),
        "fcp_ms": _ms(audits.get("first-contentful-paint")),
        "tbt_ms": _ms(audits.get("total-blocking-time")),
        "speed_index_ms": _ms(audits.get("speed-index")),
        "cls": (round(float(audits["cumulative-layout-shift"]["numericValue"]), 3)
                if (audits.get("cumulative-layout-shift") or {}).get("numericValue") is not None else None),
        "ttfb_ms": _ms(audits.get("server-response-time")),
    }

    failed: list[dict[str, Any]] = []
    blocked = 0
    for item in ((audits.get("network-requests") or {}).get("details") or {}).get("items") or []:
        code = item.get("statusCode")
        if code is None:
            continue
        if code == -1:
            blocked += 1
        elif code >= 400:
            failed.append({"url": str(item.get("url"))[:200], "status": code,
                           "type": item.get("resourceType")})
    out["failed_requests"] = failed[:10]
    out["failed_requests_count"] = len(failed)
    out["blocked_requests_count"] = blocked

    console: list[str] = []
    for item in ((audits.get("errors-in-console") or {}).get("details") or {}).get("items") or []:
        desc = str(item.get("description") or "").strip().replace("\n", " ")
        if desc:
            console.append(desc[:200])
    out["console_errors"] = console[:8]
    out["console_errors_count"] = len(console)

    a11y: list[dict[str, Any]] = []
    for ref in ((data.get("categories") or {}).get("accessibility") or {}).get("auditRefs") or []:
        audit = audits.get(ref.get("id")) or {}
        if audit.get("score") == 0 and audit.get("scoreDisplayMode") in ("binary", "numeric"):
            items = ((audit.get("details") or {}).get("items") or [])
            a11y.append({
                "id": ref.get("id"),
                "label": A11Y_AUDIT_LABELS.get(ref.get("id"), audit.get("title", ref.get("id"))),
                "count": len(items),
            })
    out["a11y_failures"] = a11y

    # Third parties: Lighthouse 13's restricted-category runs omit the third-party-summary
    # audit, so build the same table from the entity list (third-party-web mapping), the
    # network log (transfer per entity) and bootup-time (main-thread ms per script origin).
    entity_cat: dict[str, str] = {}
    origin_to_entity: dict[str, str] = {}
    for ent in data.get("entities") or []:
        if ent.get("isFirstParty"):
            continue
        name = ent.get("name", "")
        entity_cat[name] = ent.get("category") or ""
        for o in ent.get("origins") or []:
            origin_to_entity[o.rstrip("/")] = name
    agg: dict[str, dict[str, Any]] = {n: {"name": n, "category": c, "main_thread_ms": 0.0, "transfer_kb": 0.0, "requests": 0}
                                      for n, c in entity_cat.items()}
    for item in ((audits.get("network-requests") or {}).get("details") or {}).get("items") or []:
        ent = item.get("entity")
        if ent in agg:
            agg[ent]["transfer_kb"] += float(item.get("transferSize") or 0) / 1024
            agg[ent]["requests"] += 1
    for item in ((audits.get("bootup-time") or {}).get("details") or {}).get("items") or []:
        url = str(item.get("url") or "")
        try:
            from urllib.parse import urlsplit
            parts = urlsplit(url)
            origin = f"{parts.scheme}://{parts.netloc}"
        except Exception:
            continue
        ent = origin_to_entity.get(origin)
        if ent in agg:
            agg[ent]["main_thread_ms"] += float(item.get("total") or 0)
    third = [{**v, "main_thread_ms": round(v["main_thread_ms"]), "transfer_kb": round(v["transfer_kb"])} for v in agg.values()]
    third.sort(key=lambda t: (-t["main_thread_ms"], -t["transfer_kb"]))
    out["third_parties"] = third[:12]
    out["third_party_names"] = sorted(entity_cat)

    lcp_el = audits.get("largest-contentful-paint-element") or {}
    try:
        node = lcp_el["details"]["items"][0]["items"][0]["node"]
        out["lcp_element"] = str(node.get("snippet") or node.get("selector") or "")[:200]
    except Exception:
        pass
    return out


class UnlighthouseAuditor(BaseAuditor):
    """Site-wide multi-page auditing via Unlighthouse (Google Lighthouse on all discovered routes)."""

    def __init__(
        self,
        site_url,
        site,
        shared_pages=None,
        scope: str = "quick",
        target_paths: list[str] | None = None,
    ):
        super().__init__(site_url, site, shared_pages)
        self.scope = scope
        self.target_paths = target_paths or ["/"]

    def _find_chrome_path(self) -> str:
        """Locate Playwright's installed Chromium executable or system Chrome."""
        custom_env = os.environ.get("CHROME_PATH")
        if custom_env and os.path.exists(custom_env):
            return custom_env

        cache_pattern = "/root/.cache/ms-playwright/**/chrome"
        matches = glob.glob(cache_pattern, recursive=True)
        for m in matches:
            if os.path.isfile(m) and os.access(m, os.X_OK):
                return m

        for path in ["/usr/bin/google-chrome", "/usr/bin/chromium", "/usr/bin/chromium-browser"]:
            if os.path.exists(path):
                return path
        return ""

    @staticmethod
    def _write_config() -> Path:
        REPORTS_BASE_DIR.mkdir(parents=True, exist_ok=True)
        cfg = REPORTS_BASE_DIR / "_unlighthouse.config.mjs"
        content = _CONFIG_TEMPLATE % {
            "concurrency": LH_MAX_CONCURRENCY,
            "throttling": json.dumps(PSI_MOBILE_THROTTLING),
        }
        if not cfg.exists() or cfg.read_text() != content:
            cfg.write_text(content)
        return cfg

    @staticmethod
    def _park_previous_run(output_dir: Path, safe_domain: str) -> None:
        """Keep the last run's ci-result.json and per-route screenshots so this run can be
        compared against them. unlighthouse-ci wipes output_dir on start."""
        prev_dir = HISTORY_DIR / safe_domain / "previous"
        reports_dir = output_dir / "reports"
        if not reports_dir.exists():
            return
        try:
            if prev_dir.exists():
                shutil.rmtree(prev_dir)
            prev_dir.mkdir(parents=True, exist_ok=True)
            ci = output_dir / "ci-result.json"
            if ci.exists():
                shutil.copy2(ci, prev_dir / "ci-result.json")
            for shot in reports_dir.rglob("full-screenshot.jpeg"):
                rel = shot.relative_to(reports_dir)
                dest = prev_dir / rel
                dest.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(shot, dest)
        except Exception as exc:
            logger.warning("Could not park previous Lighthouse run for %s: %s", safe_domain, exc)

    @staticmethod
    def _not_measured(summary: str, details: dict[str, Any]) -> AuditModuleResult:
        """Lighthouse did not produce a result. Score None keeps it out of the overall score
        instead of inventing a number (the module used to record 50 or 0 here)."""
        return AuditModuleResult(module="unlighthouse", score=None, status="error",
                                 summary=summary, details={**details, "not_measured": True})

    async def run(self) -> AuditModuleResult:
        chrome_path = self._find_chrome_path()
        if not chrome_path:
            logger.warning("Unlighthouse: Chrome binary not found. Skipping scan.")
            return self._not_measured("Lighthouse not run: Chromium binary not found in container.",
                                      {"error": "Chromium binary missing"})

        safe_domain = _safe_domain(self.site_url)
        output_dir = REPORTS_BASE_DIR / safe_domain
        output_dir.mkdir(parents=True, exist_ok=True)
        self._park_previous_run(output_dir, safe_domain)
        config_path = self._write_config()

        env = os.environ.copy()
        env["CHROME_PATH"] = chrome_path
        env["CHROME_FLAGS"] = "--no-sandbox --disable-setuid-sandbox --disable-dev-shm-usage"

        # Always pass an explicit route list (our crawler already applied the scope). "full"
        # keeps every page for the HTML checks but samples Lighthouse to LH_MAX_ROUTES_FULL.
        paths = list(dict.fromkeys(self.target_paths or ["/"]))
        sampled = False
        if self.scope == "full" and len(paths) > LH_MAX_ROUTES_FULL:
            paths = paths[:LH_MAX_ROUTES_FULL]
            sampled = True

        cmd = [
            "unlighthouse-ci",
            "--site", self.site_url,
            "--config-file", str(config_path),
            "--samples", "1",
            "--reporter", "json",
            "--output-path", str(output_dir),
            "--cache", "false",
            "--urls", ",".join(paths),
            "--disable-sitemap", "--disable-robots-txt", "--disable-dynamic-sampling",
        ]
        # ~25s per route with two workers; floor of 5 minutes, ceiling of 45.
        timeout_seconds = min(2700.0, max(300.0, 40.0 * len(paths)))

        # Log file deliberately outside output_dir (unlighthouse-ci wipes that folder on start).
        log_file_path = REPORTS_BASE_DIR / f"{safe_domain}_unlighthouse_run.log"
        logger.info("Executing Unlighthouse scan for %s (%d routes, %.0fs budget)...",
                    self.site_url, len(paths), timeout_seconds)
        proc = None
        timed_out = False
        try:
            with open(log_file_path, "wb") as log_f:
                proc = await asyncio.create_subprocess_exec(
                    *cmd, stdout=log_f, stderr=log_f, env=env, start_new_session=True,
                )
                try:
                    await asyncio.wait_for(proc.wait(), timeout=timeout_seconds)
                except asyncio.TimeoutError:
                    timed_out = True
                    logger.warning("Unlighthouse scan timed out for %s (%.0fs limit, scope=%s)",
                                   self.site_url, timeout_seconds, self.scope)
                    self._kill_tree(proc)
                except asyncio.CancelledError:
                    self._kill_tree(proc)
                    raise
        except asyncio.CancelledError:
            raise
        except Exception as exc:
            logger.error("Failed to run unlighthouse-ci: %s", exc)
            return self._not_measured(f"Lighthouse not run: {exc}", {"error": str(exc)})

        ci_result_path = output_dir / "ci-result.json"
        if not ci_result_path.exists():
            candidates = list(output_dir.glob("**/ci-result.json"))
            if candidates:
                ci_result_path = candidates[0]

        if not ci_result_path.exists():
            try:
                log_text = log_file_path.read_text(errors="ignore")
            except OSError:
                log_text = ""
            reason = f"timed out after {timeout_seconds:.0f}s" if timed_out else "no results file was produced"
            logger.warning("Unlighthouse did not generate ci-result.json (%s): %s", reason, log_text[-300:])
            return self._not_measured(
                f"Lighthouse not measured: the scan {reason}. Routes requested: {len(paths)}.",
                {"stderr": log_text[-1500:], "timed_out": timed_out, "routes_requested": len(paths)},
            )

        try:
            routes_data = json.loads(ci_result_path.read_text(encoding="utf-8"))
        except Exception as parse_err:
            return self._not_measured(f"Lighthouse results could not be parsed: {parse_err}",
                                      {"error": str(parse_err)})

        if not isinstance(routes_data, list) or not routes_data:
            return self._not_measured("Lighthouse produced no route results.", {"routes": []})

        total_routes = len(routes_data)
        sums = {"perf": 0.0, "a11y": 0.0, "bp": 0.0, "seo": 0.0, "overall": 0.0}
        processed_routes: list[dict[str, Any]] = []
        third_party_agg: dict[str, dict[str, Any]] = {}
        runtime_entities: set[str] = set()

        for r in routes_data:
            p = round(float(r.get("performance", 0)) * 100, 1)
            a = round(float(r.get("accessibility", 0)) * 100, 1)
            b = round(float(r.get("best-practices", 0)) * 100, 1)
            s = round(float(r.get("seo", 0)) * 100, 1)
            ov = round(float(r.get("score", 0)) * 100, 1)
            sums["perf"] += p; sums["a11y"] += a; sums["bp"] += b; sums["seo"] += s; sums["overall"] += ov

            route_path = r.get("path", "/")
            if not route_path.startswith("/"):
                route_path = f"/{route_path}"
            rel_dir = Path("reports") / _route_dir(route_path)
            html_rel = rel_dir / "lighthouse.html"
            json_rel = rel_dir / "lighthouse.json"
            shot_rel = rel_dir / "full-screenshot.jpeg"

            entry: dict[str, Any] = {
                "path": route_path,
                "url": self.site_url + route_path,
                "score": ov,
                "performance": p,
                "accessibility": a,
                "best_practices": b,
                "seo": s,
                "report_url": f"/reports/{safe_domain}/{html_rel.as_posix()}" if (output_dir / html_rel).exists() else None,
                "screenshot_url": f"/reports/{safe_domain}/{shot_rel.as_posix()}" if (output_dir / shot_rel).exists() else None,
                "screenshot_file": str(output_dir / shot_rel) if (output_dir / shot_rel).exists() else None,
            }
            extra = parse_lighthouse_json(output_dir / json_rel) if (output_dir / json_rel).exists() else {}
            entry.update(extra)
            for tp in extra.get("third_parties", []):
                agg = third_party_agg.setdefault(tp["name"], {
                    "name": tp["name"], "category": tp.get("category", ""), "pages": 0,
                    "main_thread_ms_total": 0, "main_thread_ms_max": 0, "transfer_kb_total": 0,
                })
                agg["pages"] += 1
                agg["main_thread_ms_total"] += tp["main_thread_ms"]
                agg["transfer_kb_total"] += tp.get("transfer_kb", 0)
                agg["main_thread_ms_max"] = max(agg["main_thread_ms_max"], tp["main_thread_ms"])
            runtime_entities.update(extra.get("third_party_names", []))
            processed_routes.append(entry)

        avg = {k: round(v / total_routes, 1) for k, v in sums.items()}
        final_score = avg["perf"]
        worst = min(processed_routes, key=lambda x: x["performance"])
        slow_pages = [x for x in processed_routes if x["performance"] < 50]

        third_parties = sorted(third_party_agg.values(), key=lambda t: (-t["main_thread_ms_total"], -t["transfer_kb_total"]))
        for t in third_parties:
            t["main_thread_ms_avg"] = round(t["main_thread_ms_total"] / max(1, t["pages"]))
            t["transfer_kb_avg"] = round(t["transfer_kb_total"] / max(1, t["pages"]))

        html_report_path = output_dir / "reports" / "lighthouse.html"
        report_url = f"/reports/{safe_domain}/reports/lighthouse.html" if html_report_path.exists() else None

        summary = (
            f"Performance {avg['perf']:.0f}/100 averaged across {total_routes} page(s)"
            f"{' (sampled)' if sampled else ''}; slowest page {worst['path']} at {worst['performance']:.0f}. "
            f"{len(slow_pages)} page(s) below 50. "
            f"Accessibility {avg['a11y']:.0f}, Best Practices {avg['bp']:.0f}, SEO {avg['seo']:.0f}."
        )
        if third_parties and third_parties[0]["main_thread_ms_avg"] >= 100:
            top = third_parties[0]
            summary += f" Heaviest third party: {top['name']} (~{top['main_thread_ms_avg']}ms main-thread per page)."

        return AuditModuleResult(
            module="unlighthouse",
            score=final_score,
            status=self._score_to_status(final_score),
            summary=summary,
            details={
                "score_basis": "performance",
                "lab_settings": "PSI mobile (simulated, 4x CPU slowdown)",
                "total_routes_scanned": total_routes,
                "routes_requested": len(paths),
                "lighthouse_sampled": sampled,
                "site_averages": {
                    "performance": avg["perf"], "accessibility": avg["a11y"],
                    "best_practices": avg["bp"], "seo": avg["seo"], "overall": avg["overall"],
                },
                "lighthouse_composite": avg["overall"],
                "routes": processed_routes,
                "pages": processed_routes,
                "third_parties": third_parties[:20],
                "runtime_entities": sorted(runtime_entities),
                "scope": self.scope,
                "report_url": report_url,
                "report_url_label": "Homepage Lighthouse report",
                "_safe_domain": safe_domain,
            },
        )

    @staticmethod
    def _kill_tree(proc) -> None:
        """unlighthouse-ci spawns Chrome workers; killing only the node process orphaned them
        (90 idle Chrome processes were found in the container). Kill the whole session."""
        if proc is None:
            return
        try:
            os.killpg(os.getpgid(proc.pid), signal.SIGKILL)
        except Exception:
            try:
                proc.kill()
            except Exception:
                pass
